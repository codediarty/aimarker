def jong(w):
    """받침(조사 고르기). 한글은 글자로, 숫자는 읽는 소리로"""
    w = re.sub(r"[\s)\]}\"'’”.,!?·]+$", "", w)
    if not w:
        return 0
    c = ord(w[-1])
    if 0xAC00 <= c <= 0xD7A3:
        return (c - 0xAC00) % 28
    ch = w[-1].lower()
    if ch.isdigit():
        return {"0": 21, "1": 8, "3": 16, "6": 1, "7": 8, "8": 8}.get(ch, 0)
    return 4 if re.search(r"(ng|m|n|l)$", w.lower()) else 0


def jo(w, a, b):
    j = jong(w)
    if a == "으로":
        return w + ("으로" if j and j != 8 else "로")
    return w + (a if j else b)


